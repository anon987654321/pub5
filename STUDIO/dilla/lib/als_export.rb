# frozen_string_literal: true

require "json"
require "fileutils"
require_relative "als"

module Studio
  module ALS
    module Export
      module_function

      def to_json(project)
        JSON.pretty_generate(project) + "\n"
      end

      def write_json(project, path)
        write_atomic(path, to_json(project))
      end

      # The Ruby archive is deliberately self-contained: it embeds a tiny DSL
      # builder and recreates the composition as ordinary Ruby data.
      def to_ruby(project)
        lines = []
        lines << "# frozen_string_literal: true"
        lines << "# Ableton Live Set composition archive; generated by Studio::ALS."
        lines << "# Audio files and native device state remain external references."
        lines << ""
        lines << "class AbletonArchiveBuilder"
        lines << "  def project(attributes, &block)"
        lines << '    @project = attributes.merge("tracks" => [], "automation" => [])'
        lines << "    instance_exec(&block) if block"
        lines << "    @project"
        lines << "  end"
        lines << ""
        lines << "  def track(attributes, &block)"
        lines << '    item = attributes.merge("clips" => [], "automation" => [])'
        lines << '    @project.fetch("tracks") << item'
        lines << "    previous = @track"
        lines << "    @track = item"
        lines << "    instance_exec(&block) if block"
        lines << "    @track = previous"
        lines << "    item"
        lines << "  end"
        lines << ""
        lines << "  def clip(attributes, &block)"
        lines << '    item = attributes.merge("notes" => [], "audio_references" => [], "automation" => [])'
        lines << '    @track.fetch("clips") << item'
        lines << "    previous = @clip"
        lines << "    @clip = item"
        lines << "    instance_exec(&block) if block"
        lines << "    @clip = previous"
        lines << "    item"
        lines << "  end"
        lines << ""
        lines << '  def note(attributes) = @clip.fetch("notes") << attributes'
        lines << '  def automation(attributes)'
        lines << '    target = @clip || @track || @project'
        lines << '    (target["automation"] ||= []) << attributes'
        lines << '  end'
        lines << '  def audio_reference(attributes) = @clip.fetch("audio_references") << attributes'
        lines << "end"
        lines << ""
        lines << "PROJECT = AbletonArchiveBuilder.new.project(#{literal(project.reject { |key, _| key == "tracks" })}) do"

        Array(project["tracks"]).each do |track|
          track_attributes = track.reject { |key, _| key == "clips" }
          lines << "  track(#{literal(track_attributes)}) do"
          Array(track["clips"]).each do |clip|
            clip_attributes = clip.reject { |key, _| %w[notes audio_references automation].include?(key) }
            lines << "    clip(#{literal(clip_attributes)}) do"
            Array(clip["notes"]).each { |note| lines << "      note(#{literal(note)})" }
            Array(clip["audio_references"]).each { |reference| lines << "      audio_reference(#{literal(reference)})" }
            Array(clip["automation"]).each { |envelope| lines << "      automation(#{literal(envelope)})" }
            lines << "    end"
          end
          Array(track["automation"]).each { |envelope| lines << "    automation(#{literal(envelope)})" }
          lines << "  end"
        end
        lines << "end"
        lines.join("\n") + "\n"
      end

      def write_ruby(project, path)
        write_atomic(path, to_ruby(project))
      end

      def write_both(project, json_path:, ruby_path:)
        write_json(project, json_path)
        write_ruby(project, ruby_path)
        { json: File.expand_path(json_path), ruby: File.expand_path(ruby_path) }
      end

      def write_atomic(path, content)
        destination = File.expand_path(path)
        FileUtils.mkdir_p(File.dirname(destination))
        temporary = "#{destination}.tmp-#{Process.pid}"
        File.binwrite(temporary, content)
        File.rename(temporary, destination)
        destination
      ensure
        File.delete(temporary) if temporary && File.exist?(temporary)
      end

      def literal(value)
        case value
        when Hash
          "{ " + value.map { |key, item| "#{key.to_s.dump} => #{literal(item)}" }.join(", ") + " }"
        when Array
          "[ " + value.map { |item| literal(item) }.join(", ") + " ]"
        when String
          value.dump
        when Numeric, TrueClass, FalseClass, NilClass
          value.inspect
        else
          value.to_s.dump
        end
      end
    end
  end
end

if $PROGRAM_NAME == __FILE__
  require "optparse"
  input = ARGV.shift
  abort "usage: ruby als_export.rb SET.als [--json PATH] [--ruby PATH]" unless input

  base = File.join(File.dirname(File.expand_path(input)), File.basename(input, File.extname(input)))
  json_path = "#{base}.json"
  ruby_path = "#{base}.rb"
  OptionParser.new do |parser|
    parser.on("--json PATH", "JSON composition archive path") { |value| json_path = value }
    parser.on("--ruby PATH", "Standalone Ruby DSL archive path") { |value| ruby_path = value }
  end.parse!(ARGV)

  project = Studio::ALS::Parser.new.parse(input)
  outputs = Studio::ALS::Export.write_both(project, json_path:, ruby_path:)
  puts "als-export: #{project.fetch("tracks").length} tracks, #{outputs.fetch(:json)}, #{outputs.fetch(:ruby)}"
end
