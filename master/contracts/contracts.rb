# frozen_string_literal: true

require_relative "../../core/core"

# The coordination contract every contributor reads (AGENTS.md: Codex,
# Copilot, Grok, GLM, Gemini, Cursor; CLAUDE.md points to it). It is
# rendered from registry/writers.yml and registry/laws.yml, so who writes
# where and which Laws bind cannot drift from the registries;
# GENERATED_FILE_MATCHES_GENERATOR fails a hand edit.
module Contracts
  module_function

  def generated?(file) = Core::Registry.load(:paths).fetch("generated").key?(file)

  def render(file)
    case file
    when "AGENTS.md" then agents
    when "CLAUDE.md" then "Read AGENTS.md first; it is the contract for every writer, Claude included.\n"
    else raise Core::Refusal.new(:render, file, "no generator")
    end
  end

  def agents
    writers = Core::Registry.load(:writers).fetch("writers")
    laws = Core::Registry.load(:laws).fetch("laws")
    main, inbox = writers.partition { |_, w| w["trust"] == "main" }
    ruby = File.read(File.join(Core::ROOT, ".ruby-version")).strip
    <<~MD
      <!-- Generated by `bin/master generate` from registry/writers.yml and
           registry/laws.yml. Edit those; GENERATED_FILE_MATCHES_GENERATOR fails a hand edit. -->
      # Contract for every writer of pub5

      PLAN.md is the plan; where this file and PLAN.md disagree, PLAN.md wins and the
      commit says why. This file is the rule for anyone who changes the tree:
      Codex, Copilot, Grok, GLM, Gemini, Cursor and Claude alike.

      ## Who writes where
      - #{main.map(&:first).join(' and ')} push straight to `main`, and only behind the gate below.
      - #{inbox.map(&:first).join(', ')} push only to `inbox/<writer>`, one task per branch.
        An inbox branch merges when the gate is green, a different model reviewed it,
        and every changed path sits under that writer's trees:
      #{inbox.map { |name, w| "  - #{name}: #{w['trees'].join(', ')}" }.join("\n")}
      - Never force-push. Fetch and rebase before every push; if another writer's commit
        touches your files, keep their change and adapt yours. A commit that breaks the
        gate is fixed in a separate commit naming the one it repairs.

      ## How the port works
      - Move, then clean. The Rails apps, dilla, the TTS engines and the face renderer
        move from pub4 and are cleaned here, not rewritten; only core, the registries,
        the Law engine and /fix are new code (PLAN.md section 14).
      - Lock before moving: a behaviour that moves has an executable contract in pub4
        first (pub4 MASTER/checks/data/route_contracts/ and MASTER/test/). Without
        one, moving it is a new feature, and new features wait.
      - Same behaviour, less code. A moved file that satisfies no contract does not belong.
      - pub4 is the archive, never the workspace: no pub5 commit names pub4 as its
        working tree, and the first commit of each work stream names the pub4 commit
        it moved from.
      - One Ruby version, #{ruby} (.ruby-version), the one the deploy host runs. Scripts
        are Ruby, data is YAML or JSON; no Python, no sed or coreutils text work.
      - Run output (log/, tmp/, coverage/, snapshots) never enters git.

      ## The gate
      - Every push passes parse (Ruby, YAML, JSON, ERB), the tests for the touched trees,
        and the enforced Laws on the diff.
      - pub5 gates itself: no GitHub Actions or other third-party CI (operator, 2026-11-06).
        Every writer runs `bin/check` before every push and pushes only when it is green;
        `bin/setup` installs the pre-commit hook (`bin/master check --staged`) and the
        commit-msg check. `bin/lint` and `bin/test` run its halves.
      - pub5's own gatekeeper judges every pushed commit, and merges an `inbox/<writer>`
        branch only when `bin/check` is green on it.
      - Run the tests you claim to have run, and name them in the commit body. The GLM
        and Fable patches of 2026-11-06 claimed fixes and ran no tests.
      - A result you did not measure is INCONCLUSIVE or BLOCKED, never PASS. Mark
        anything you did not run as NOT_RUN.

      ## Read the governing manual first
      - Before editing rails/: the Rails style guide (github.com/rubocop/rails-style-guide)
        and the Rails edge guides (edgeguides.rubyonrails.org) for every API you touch.
      - Before editing openbsd/: the man page of every tool, daemon or config file you touch.
      - Name the guide section or man page in the commit body.

      ## Commit format
      - Subject: imperative, capitalised, plain ASCII, at least two words, at most 72
        characters, one line, no type prefix, no trailing punctuation.
      - Body: what changed, why, and how it was proven.
      - One task per commit, scoped to its paths. AI writers end with their
        Co-Authored-By trailer.

      ## Where things live
      - core/: the only code that touches files, processes, network, models, git and the
        environment. Everything else calls it.
      - registry/: one registry per concern, each with a schema in registry/schemas/.
        Environment variables must be declared in registry/knobs.yml.
      - laws/: one file per Law (detector and bad/good fixtures, proved at load);
        registry/laws.yml holds each Law's statement, kind, severity, lifecycle and census.
      - registry/paths.yml lists protected paths; no automated writer changes them.
      - bin/master is the one entrypoint; registry/commands.yml lists its commands.

      ## Laws in force (#{laws.count { |_, l| l['lifecycle'] == 'enforced' }} enforced, #{laws.size} total)
      #{listed(laws.select { |_, l| l['lifecycle'] == 'enforced' })}
      
      The other #{laws.count { |_, l| l['lifecycle'] != 'enforced' }} are advisory (#{advisory(laws)}): each is in
      registry/laws.yml with its statement, and `bin/master laws` lists them.
      
      ## Conduct every writer keeps (#{conduct(laws).size} conduct Laws, advisory)
      #{listed(conduct(laws))}
    MD
  end

  def listed(laws) = laws.map { |id, l| "- #{id} (#{l['lifecycle']}, #{l['severity']}): #{l['statement']}" }.join("\n")

  def conduct(laws) = laws.select { |_, l| l["kind"] == "conduct" && l["lifecycle"] != "enforced" }

  def advisory(laws)
    laws.reject { |_, l| l["lifecycle"] == "enforced" }.group_by { |_, l| l["kind"] }
        .sort_by { |kind, _| kind }.map { |kind, rows| "#{rows.size} #{kind}" }.join(", ")
  end
end
